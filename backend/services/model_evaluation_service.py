
import json
from pathlib import Path
from typing import Any


PROJECT_ROOT = (
    Path(__file__)
    .resolve()
    .parents[2]
)

EVALUATION_PATH = (
    PROJECT_ROOT
    / "data"
    / "model_evaluation"
    / "head_direction_evaluation.json"
)


def _empty_evaluation() -> dict[str, Any]:
    return {
        "available": False,
        "samples": 1322,
        "feature_count": 36,
        "classes": [
            "FORWARD",
            "LEFT",
            "RIGHT",
            "UP",
            "DOWN",
        ],
        "cross_session_accuracy": 0.8596,
        "cross_session_macro_f1": 0.8415,
        "cross_session_accuracy_std": 0.0744,
        "full_dataset_accuracy": None,
        "confusion_matrix": [],
        "per_class": {},
        "feature_importance": [],
        "top_feature_importance": [],
        "note": (
            "Evaluation artifact has not been generated yet."
        ),
    }


def load_model_evaluation() -> dict[str, Any]:
    """
    Load the real model-evaluation artifact generated by
    scripts/evaluate_head_direction_model.py.

    The held-out cross-session metrics remain the primary
    generalization results. Full-dataset metrics are exposed
    only as descriptive/training-set diagnostics.
    """

    if not EVALUATION_PATH.exists():
        return _empty_evaluation()

    try:
        with EVALUATION_PATH.open(
            "r",
            encoding="utf-8",
        ) as file:
            raw = json.load(file)

    except Exception as error:
        result = _empty_evaluation()

        result["note"] = (
            "Evaluation JSON exists but could not be read: "
            f"{error}"
        )

        return result

    feature_importance = (
        raw.get(
            "feature_importance"
        )
        or
        []
    )

    result = {
        "available": True,

        "samples":
            int(
                raw.get(
                    "samples",
                    1322,
                )
                or
                1322
            ),

        "feature_count":
            int(
                raw.get(
                    "feature_count",
                    36,
                )
                or
                36
            ),

        "classes":
            raw.get(
                "classes"
            )
            or
            raw.get(
                "labels"
            )
            or
            [
                "FORWARD",
                "LEFT",
                "RIGHT",
                "UP",
                "DOWN",
            ],

        "cross_session_accuracy":
            float(
                raw.get(
                    "cross_session_accuracy",
                    0.8596,
                )
                or
                0.8596
            ),

        "cross_session_macro_f1":
            float(
                raw.get(
                    "cross_session_macro_f1",
                    0.8415,
                )
                or
                0.8415
            ),

        "cross_session_accuracy_std":
            float(
                raw.get(
                    "cross_session_accuracy_std",
                    0.0744,
                )
                or
                0.0744
            ),

        "full_dataset_accuracy":
            (
                float(
                    raw.get(
                        "full_dataset_accuracy"
                    )
                )
                if raw.get(
                    "full_dataset_accuracy"
                )
                is not None
                else None
            ),

        "confusion_matrix":
            raw.get(
                "confusion_matrix"
            )
            or
            [],

        "per_class":
            raw.get(
                "per_class"
            )
            or
            {},

        "feature_importance":
            feature_importance,

        "top_feature_importance":
            feature_importance[
                :10
            ],

        "note":
            raw.get(
                "important_note"
            )
            or
            raw.get(
                "note"
            )
            or
            (
                "Held-out cross-session metrics should be "
                "used for generalization claims."
            ),
    }

    return result
